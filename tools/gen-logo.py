#!/usr/bin/env python3
"""
The ROBOSECT logo D3 «Capocorda» in the site, from the client-approved kit. Do not edit the files below by hand: re-run
this (from the site folder) whenever the kit changes, then `node tools/gen-og.mjs` for the social images.

    python3 tools/gen-logo.py            (reads ../robosect-brand/logo-D3; LOGO_KIT=/path/to/logo-D3 for another copy)

Writes
  src/lib/cable-geometry.ts           the hero's R as a stroke: centreline, cable width, ferrule parts, N1 letters, clear space
                                      (the hero and the footer size themselves from it: nothing to copy by hand)
  src/scripts/panel/robot/logo.ts     the print on every robot arm: the wordmark, and the small-cut R where the arm is small
  src/assets/brand/                   the logotype for the nav and the footer (negativo, on ink), verbatim
  public/                             the site icons (05-kit/03-icone) and the LinkedIn avatar, verbatim
  src/content/blog/2026-02-01_AIRISE_KICKOFF/logos.png   the AIRISE.EU + ROBOSECT strip of that post

Nothing is redrawn: every shape is the kit's path data, verbatim. The R's centreline is derived from its outline (the two
sides of the cable, paired segment by segment) and checked: concentric arcs, parallel runs, one width everywhere.
"""
import json, math, os, re, shutil

from PIL import Image

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIT = os.environ.get('LOGO_KIT', os.path.join(os.path.dirname(SITE), 'robosect-brand', 'logo-D3'))
K5 = KIT + '/05-kit'
HEAD = '/* Generated by tools/gen-logo.py from the logo kit D3 «Capocorda» (robosect-brand/logo-D3): do not edit by hand. */\n'


def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def svg_parts(path):
    """(viewBox floats, [(fill, d)]) of a kit SVG"""
    s = read(path)
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', s).group(1).split()]
    return vb, re.findall(r'<path fill="(#[0-9A-Fa-f]{6})" d="([^"]+)"', s)


def subpaths(d):
    return ['M' + p for p in d.split('M') if p.strip()]


def tokens(d):
    return re.findall(r'[A-Za-z]|-?\d*\.?\d+(?:e-?\d+)?', d)


def segments(sub):
    """the absolute M/L/A/Z segments of one subpath: ('L', p0, p1) | ('A', p0, p1, r, large, sweep)"""
    t = tokens(sub)
    i, cmd, cur, start, out = 0, None, None, None, []
    while i < len(t):
        if t[i].isalpha():
            cmd = t[i]
            i += 1
            if cmd == 'Z':
                if cur != start:
                    out.append(('L', cur, start))
                cur = start
                continue
        if cmd == 'M':
            cur = start = (float(t[i]), float(t[i + 1]))
            i += 2
            cmd = 'L'
        elif cmd == 'L':
            p = (float(t[i]), float(t[i + 1]))
            out.append(('L', cur, p))
            cur = p
            i += 2
        elif cmd == 'A':
            r, rr, _, large, sweep, x, y = (float(v) for v in t[i : i + 7])
            assert r == rr, 'circular arcs only'
            p = (x, y)
            out.append(('A', cur, p, r, int(large), int(sweep)))
            cur = p
            i += 7
        else:
            raise ValueError('unexpected command ' + str(cmd))
    return out


def centre(s):
    """the centre of a circular arc segment (SVG endpoint parameterisation)"""
    _, (x0, y0), (x1, y1), r, large, sweep = s
    mx, my = (x0 + x1) / 2, (y0 + y1) / 2
    dx, dy = x1 - x0, y1 - y0
    q = math.hypot(dx, dy)
    h = math.sqrt(max(0.0, r * r - (q / 2) ** 2))
    sgn = 1 if large != sweep else -1
    return (mx - sgn * h * dy / q, my + sgn * h * dx / q)


def xs(d):
    """every x of a path's points (end and control points; M L H V Q A, absolute)"""
    t, i, cmd, out = tokens(d), 0, None, []
    n = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'Q': 4, 'A': 7, 'Z': 0}
    while i < len(t):
        if t[i].isalpha():
            cmd = t[i]
            i += 1
            continue
        a = [float(v) for v in t[i : i + n[cmd]]]
        i += n[cmd]
        out += {'H': a, 'V': [], 'A': a[5:6]}.get(cmd, a[0::2])
    return out


def near(a, b, eps=1e-3):
    return abs(a - b) < eps


def mid(p, q):
    return ((p[0] + q[0]) / 2, (p[1] + q[1]) / 2)


def num(v):
    s = ('%.3f' % v).rstrip('0').rstrip('.')
    return '0' if s == '-0' else s


# ------------------------------------------------------------------ sources
_, R_A = svg_parts(KIT + '/01-R/svg/R-A.svg')
WVB, WORD = svg_parts(K5 + '/01-logotipo/robosect-logotipo-colore-stretto.svg')
NVB, NEG = svg_parts(K5 + '/01-logotipo/robosect-logotipo-negativo-stretto.svg')
SVB, SMALL = svg_parts(KIT + '/03-simbolo/svg/simbolo-piccolo.svg')

(blue, r_d), (copper, cu_d) = R_A
r_sub = subpaths(r_d)
cable_d, collar_d = r_sub[0], r_sub[1]
word_sub = subpaths(WORD[0][1])
# the logotype's R is the chosen R, verbatim (the kit's build checks it; checked again here)
assert word_sub[0] == cable_d and word_sub[1] == collar_d and WORD[1][1] == cu_d, 'the logotype R is not R-A.svg'
assert NEG[0][1] == WORD[0][1] and NEG[1][1] == WORD[1][1], 'negativo and colore differ in shape'
letters_d = ''.join(word_sub[2:])

# ------------------------------------------------------------------ the R's centreline, from its outline
segs = segments(cable_d)
foot_cut = segs[-1]  # the closing segment: the flat cut of the stem foot, on the baseline
n = len(segs) - 1
assert n % 2 == 1, 'outline: side, end cut, side, foot cut'
k = n // 2
end_cut = segs[k]  # the flat cut where the cable meets the ferrule
side_a, side_b = segs[:k], segs[k + 1 : n][::-1]
w = math.dist(foot_cut[1], foot_cut[2])
assert foot_cut[0] == 'L' and end_cut[0] == 'L' and near(math.dist(end_cut[1], end_cut[2]), w), 'two flat cuts, one width'
fwd = []  # stem foot -> the cable's end, along the middle of the cable
for a, b in zip(side_a, side_b):
    assert a[0] == b[0], 'the two sides pair segment by segment'
    p0, p1 = mid(a[1], b[2]), mid(a[2], b[1])
    if a[0] == 'L':
        fwd.append(('L', p0, p1))
    else:
        ca, cb = centre(a), centre(b)
        assert near(ca[0], cb[0]) and near(ca[1], cb[1]) and near(abs(a[3] - b[3]), w), 'concentric arcs, one width'
        fwd.append(('A', p0, p1, (a[3] + b[3]) / 2, a[4], a[5]))
    if a[0] == 'L':  # parallel runs at distance w
        ux, uy = a[2][0] - a[1][0], a[2][1] - a[1][1]
        L = math.hypot(ux, uy)
        dist = abs((b[1][0] - a[1][0]) * uy - (b[1][1] - a[1][1]) * ux) / L
        assert near(dist, w), 'parallel runs, one width'
for s0, s1 in zip(fwd, fwd[1:]):
    assert near(s0[2][0], s1[1][0]) and near(s0[2][1], s1[1][1]), 'a continuous centreline'
foot, end = fwd[0][1], fwd[-1][2]
# rD runs from the cable's end at the ferrule back to the stem foot: the page lead continues straight down from the stem
rD = 'M %s %s' % (num(end[0]), num(end[1]))
for s in reversed(fwd):
    if s[0] == 'L':
        rD += ' L %s %s' % (num(s[1][0]), num(s[1][1]))
    else:
        rD += ' A %s %s 0 %d %d %s %s' % (num(s[3]), num(s[3]), s[4], 1 - s[5], num(s[1][0]), num(s[1][1]))

# the ferrule: the insulating collar (cable colour) and the copper (crimped tube + strands); its extent and axis
cu_x = [float(v) for v in re.findall(r'-?\d*\.?\d+', cu_d)][0::2]  # rectangles: M x y L x y …
cu_y = [float(v) for v in re.findall(r'-?\d*\.?\d+', cu_d)][1::2]
assert set(re.findall(r'[A-Za-z]', cu_d)) <= {'M', 'L', 'Z'}
col = segments(collar_d)
x0 = min(min(s[1][0], s[2][0]) for s in col)
x1 = max(cu_x)
fy = (min(cu_y) + max(cu_y)) / 2
assert near(fy, end[1]), 'the ferrule sits on the cable axis'
# the O's left edge (the first letter after the R): the descriptor aligns there on phones
o_left = min(xs(word_sub[2]))
# the clear space: the ferrule's length past the cable's end (the kit's margin around the logotype and the symbol)
clear = x1 - end[0]
assert near(-svg_parts(K5 + '/01-logotipo/robosect-logotipo-colore.svg')[0][0], clear), 'clear space is not the ferrule length'

geo = f'''{HEAD}/**
 * The cable R of the ROBOSECT logotype (logo D3 «Capocorda», N1), for the hero wordmark drawn as a stroke and the page cable.
 * Units: cap height = 96. The R is one cable of width `w`: a tangent-continuous centreline (lines + constant-radius arcs).
 * rD runs from the cable's end at the ferrule back to the stem foot, so the page cable can continue straight down from the
 * stem: the R is where the cable starts. The ferrule (insulating collar + copper tube with strands) crimps the other end.
 */
export const R_GEOMETRY = {{
	cap: 96,
	/** cable width (the stroke of rD), in cap units */
	w: {num(w)},
	/** wordmark box (the kit's «-stretto» logotype): x 0..W, y top..bot */
	W: {num(WVB[2])},
	top: {num(WVB[1])},
	bot: {num(WVB[1] + WVB[3])},
	/** stem centreline x and the stem foot (flat cut on the baseline) */
	stemX: {num(foot[0])},
	stemFootY: {num(foot[1])},
	/** left edge of the O: the hero's descriptor aligns here on phones */
	oLeft: {num(o_left)},
	/** the clear space around the logo: the ferrule's length (nothing else inside it) */
	clear: {num(clear)},
	/** centreline of the R, the cable's end at the ferrule -> stem foot */
	rD: '{rD}',
	/** the ferrule: x0 (the collar's mouth) .. x1 (the strands' tip) on the axis y; the collar (cable colour) and the copper */
	ferrule: {{
		x0: {num(x0)},
		x1: {num(x1)},
		y: {num(fy)},
		collar: '{collar_d}',
		cu: '{cu_d}',
	}},
	/** O-B-O-S-E-C-T outlines (N1: Space Grotesk 400, tracking -2), filled */
	letters: '{letters_d}',
}} as const;
'''

# ------------------------------------------------------------------ the arm print
# the wordmark: the colour logotype as is (the arm's link is Carta); the R where the arm is small: the small cut (the kit's
# R retouched for small sizes: thicker cable, wider gap, one copper block), the drawing of 03-simbolo, margin of 30 removed
MARGIN = clear
assert near(SVB[0], -MARGIN) and near(SVB[1], -MARGIN)
box = lambda vb: '{ x: %s, y: %s, w: %s, h: %s }' % tuple(num(v) for v in vb)
arm = f'''{HEAD}/**
 * The ROBOSECT logo on every robot's forearm (client note 16). The artwork is the logo kit's own path data, verbatim, literal
 * paint (client note 9): the colour logotype where the arm is drawn large enough, the small-cut R (the kit's R retouched for
 * small sizes) elsewhere. robot/draw.ts draws it into each arm's link group once (persistent nodes).
 */
/** each drawing's box (cap height 96): the logotype «-stretto», the small-cut R without its margin */
export const LOGO_BOX = {{ w: {box(WVB)}, r: {box([SVB[0] + MARGIN, SVB[1] + MARGIN, SVB[2] - 2 * MARGIN, SVB[3] - 2 * MARGIN])} }};
/** [fill, d] per path, in the files' order */
export const LOGO_W: [string, string][] = {json.dumps([[f, d] for f, d in WORD])};
export const LOGO_R: [string, string][] = {json.dumps([[f, d] for f, d in SMALL])};
'''

with open(SITE + '/src/lib/cable-geometry.ts', 'w', encoding='utf-8') as f:
    f.write(geo)
with open(SITE + '/src/scripts/panel/robot/logo.ts', 'w', encoding='utf-8') as f:
    f.write(arm)

# ------------------------------------------------------------------ files used as they are
COPY = {
    K5 + '/01-logotipo/robosect-logotipo-negativo-stretto.svg': 'src/assets/brand/robosect-logotipo-negativo-stretto.svg',
    K5 + '/02-simbolo/robosect-simbolo-linkedin-400.png': 'public/avatar-400.png',
}
for name in ('favicon.ico', 'apple-touch-icon.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'site.webmanifest'):
    COPY[K5 + '/03-icone/' + name] = 'public/' + name
for src, dst in COPY.items():
    shutil.copyfile(src, SITE + '/' + dst)

# ------------------------------------------------------------------ the AIRISE.EU + ROBOSECT strip (a news post's cover)
# the AIRISE.EU logo (the site's own file) on top, the colour logotype under it with its margin, on white
air = Image.open(SITE + '/src/assets/images/home/logo-airise.png').convert('RGBA')
logo = Image.open(K5 + '/01-logotipo/robosect-logotipo-colore-2400.png').convert('RGBA')
lw = air.width
lh = round(logo.height * lw / logo.width)
strip = Image.new('RGBA', (lw, air.height + lh), (255, 255, 255, 255))
strip.alpha_composite(air, (0, 0))
strip.alpha_composite(logo.resize((lw, lh), Image.LANCZOS), (0, air.height))
strip.convert('RGB').save(SITE + '/src/content/blog/2026-02-01_AIRISE_KICKOFF/logos.png', optimize=True)

print('w', num(w), 'stem', foot, 'end', end, 'ferrule', num(x0), num(x1), num(fy), 'O', num(o_left), 'clear', num(clear), 'W', num(WVB[2]))
print('rD', rD)
